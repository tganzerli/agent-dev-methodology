#!/usr/bin/env python3
"""Deterministic generator for a knowledge sub-index.

Reads the frontmatter of <vault>/<dir>/*.md and emits <vault>/<dir>/_index.md, one
line per page: `- [[dir/page]] — summary · _status_`.

Why it exists: every hand-maintained sub-index in one installation drifted, and the
only generated one did not — decisions/ was missing 10 of 27 ADRs, cross-cutting/ 7 of
17, while the generated work index had 0 of 108 missing. The defect is always
omission, never invention, so it is silent: a reader cannot see what is not listed.

Directory-agnostic: what changes between catalogs is the DIRS entry, not the machinery.
An unlisted directory still works with defaults (no type check; date order if every
name is date-prefixed, else alphabetical).

Idempotent; standard library only; shares the frontmatter parser of work-index.

Usage:
  python3 generate.py <dir> [--root .] [--vault NAME] [--check] [--verbose] [--label KEY=VALUE ...]
  python3 generate.py --all [--check]     # every configured dir that has pages

  --check    do not write; exit 1 if the file on disk differs (drift).
  --label    override one catalog label for this run (see LABELS below).

Labels (titles and headings) default to English. A vault written in another language
translates them once, in the `catalog-labels` block of <vault>/_meta/conventions.md:
  - `decisions`: <title>      (also `cross-cutting`, `sources/external`, `postmortems`,
                              or any other dir passed explicitly)
  - `pages`: <heading with {n}>          e.g. `Pages ({n})`
  - `generated`: <one-line banner with {dir}>
The block is read on every run (so /wiki-lint's drift check sees the same labels);
`--label` overrides it for one run.
Exit: 0 ok · 1 drift · 2 usage · 3 no pages in the directory (nothing to generate).
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "work-index"))
from generate import find_vault, parse_frontmatter  # noqa: E402  (same vault, same dialect)

# `expect_type=None` turns the type check off: cross-cutting/ mixes types by nature.
DIRS = {
    "decisions": dict(title="Decisions — Architecture Decision Records", expect_type="adr",
                      sort="date_desc"),
    "cross-cutting": dict(title="Cross-cutting — knowledge that crosses boundaries",
                          expect_type=None, sort="name"),
    "sources/external": dict(title="External sources — ingested summaries", expect_type="source",
                             sort="date_desc"),
    "postmortems": dict(title="Postmortems — lessons from costly bugs", expect_type="postmortem",
                        sort="date_desc"),
}
DATE_SLUG = re.compile(r"^(\d{4}-\d{2}-\d{2})_")
# One line per entry, not a paragraph. A catalog entry that became a digest is a
# structural cause of prefix bloat (METHODOLOGY §6.6); /wiki-lint gates on this limit.
MAX_SUMMARY = 250
NO_PAGES = 3  # distinct from drift (1): nothing to index is not something to regenerate

# Catalog labels: the defaults render exactly the English catalog. Overrides come from the
# `catalog-labels` block of <vault>/_meta/conventions.md, then from --label.
LABELS_BEGIN, LABELS_END = "<!-- catalog-labels:begin -->", "<!-- catalog-labels:end -->"
DEFAULT_PAGES = "Pages ({n})"
DEFAULT_BANNER = [
    "> **GENERATED by `/wiki-index {dir}` — do not edit by hand.** Adjust the page's",
    "> frontmatter (`summary`, `status`) and regenerate. `_meta/index.md` points here",
    "> instead of repeating the list — a second copy drifts from the first.",
]


def read_labels(root, vault):
    """{key: value} from the conventions block; {} when absent (defaults apply)."""
    path = os.path.join(root, vault, "_meta", "conventions.md")
    try:
        text = open(path, encoding="utf-8").read()
    except OSError:
        return {}
    a, b = text.find(LABELS_BEGIN), text.find(LABELS_END)
    if a == -1 or b < a:
        return {}
    labels = {}
    for line in text[a + len(LABELS_BEGIN):b].splitlines():
        m = re.match(r"^\s*-\s*`([^`]+)`\s*:\s*(.+?)\s*$", line)
        if m:
            labels[m.group(1)] = m.group(2)
    return labels


def config(dirname, names):
    if dirname in DIRS:
        return DIRS[dirname]
    dated = names and all(DATE_SLUG.match(n) for n in names)
    return dict(title=dirname, expect_type=None, sort="date_desc" if dated else "name")


def load_pages(root, vault, dirname):
    """A page with bad frontmatter still appears, degraded — dropping it would bring
    back the very invisibility this generator exists to remove."""
    pages, warnings = [], []
    for fp in sorted(glob.glob(os.path.join(root, vault, dirname, "*.md"))):
        name = os.path.basename(fp)[:-3]
        if name.startswith("_"):
            continue
        with open(fp, encoding="utf-8") as fh:
            fm = parse_frontmatter(fh.read())
        summary = " ".join(str(fm.get("summary") or "").split())
        if not summary:
            summary = str(fm.get("title") or name).strip()
            warnings.append(f"{dirname}/{name}: no `summary` — line degraded to the title")
        if len(summary) > MAX_SUMMARY:
            warnings.append(f"{dirname}/{name}: summary has {len(summary)} chars "
                            f"(limit {MAX_SUMMARY}) — the catalog entry became a digest")
        m = DATE_SLUG.match(name)
        pages.append(dict(name=name, date=m.group(1) if m else "", summary=summary,
                          type=fm.get("type"), status=str(fm.get("status") or "").strip(),
                          updated=str(fm.get("updated") or "").strip()))
    cfg = config(dirname, [p["name"] for p in pages])
    for p in pages:
        if cfg["expect_type"] and p["type"] != cfg["expect_type"]:
            warnings.append(f"{dirname}/{p['name']}: type={p['type']!r}, "
                            f"expected {cfg['expect_type']!r}")
    return pages, warnings, cfg


def render(dirname, cfg, pages, labels=None):
    labels = labels or {}
    title = labels.get(dirname, cfg["title"])
    banner = ([f"> {labels['generated']}".replace("{dir}", dirname)] if "generated" in labels
              else [l.replace("{dir}", dirname) for l in DEFAULT_BANNER])
    out = [
        "---", f"title: {title}", "type: index", "status: generated",
        "updated: " + max((p["updated"] for p in pages if p["updated"]), default=""),
        "---", "",
        f"# {title}", "",
        *banner, "",
        "## " + labels.get("pages", DEFAULT_PAGES).replace("{n}", str(len(pages))), "",
    ]
    if cfg["sort"] == "date_desc":
        ordered = sorted(pages, key=lambda p: (p["date"], p["name"]), reverse=True)
    else:
        ordered = sorted(pages, key=lambda p: p["name"])
    for p in ordered:
        line = f"- [[{dirname}/{p['name']}]] — {p['summary']}"
        if p["status"]:
            line += f" · _{p['status']}_"
        out.append(line)
    out.append("")
    return "\n".join(out)


def run(root, vault, dirname, check, verbose, labels=None):
    """Returns 0 in sync/written, 1 drift, None when the dir has no pages."""
    pages, warnings, cfg = load_pages(root, vault, dirname)
    if not pages:
        return None
    for w in warnings:
        print(f"⚠  {w}", file=sys.stderr)
    if verbose:
        for p in pages:
            print(f"   {p['name']}", file=sys.stderr)
    body = render(dirname, cfg, pages, labels)
    target = os.path.join(root, vault, dirname, "_index.md")
    current = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
    if check:
        if current != body:
            print(f"drift: {vault}/{dirname}/_index.md", file=sys.stderr)
            return 1
        print(f"{dirname}: {len(pages)} pages, in sync", file=sys.stderr)
        return 0
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(body)
    print(f"{dirname}: {len(pages)} pages, written", file=sys.stderr)
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir", nargs="?", help="vault sub-directory to index (e.g. decisions)")
    ap.add_argument("--all", action="store_true", help="every configured dir that has pages")
    ap.add_argument("--root", default=os.getcwd())
    ap.add_argument("--vault", default=None)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument("--label", action="append", default=[], metavar="KEY=VALUE",
                    help="override a catalog label for this run (repeatable)")
    a = ap.parse_args()
    if bool(a.dir) == a.all:
        ap.error("pass exactly one of <dir> or --all")
    vault = a.vault or find_vault(a.root)
    if not vault:
        sys.exit("no *_wiki vault found under --root; pass --vault <name>")
    labels = read_labels(a.root, vault)
    for kv in a.label:
        if "=" not in kv:
            ap.error(f"--label expects KEY=VALUE, got {kv!r}")
        k, v = kv.split("=", 1)
        labels[k.strip()] = v.strip()

    if a.all:
        results = [run(a.root, vault, d, a.check, a.verbose, labels) for d in DIRS]
        return 1 if any(r == 1 for r in results) else 0
    if not os.path.isdir(os.path.join(a.root, vault, a.dir)):
        print(f"{vault}/{a.dir}/ does not exist", file=sys.stderr)
        return NO_PAGES
    r = run(a.root, vault, a.dir.rstrip("/"), a.check, a.verbose, labels)
    if r is None:
        print(f"no pages in {vault}/{a.dir}/ — refusing to write an empty catalog", file=sys.stderr)
        return NO_PAGES
    return r


if __name__ == "__main__":
    sys.exit(main())
